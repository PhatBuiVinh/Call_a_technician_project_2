export function toSuburbSlug(name) {
  const postcode = SUBURB_POSTCODES[name];
  const slug = name
    .toLowerCase()
    .replace(/'/g, "")
    .replace(/\./g, "")
    .replace(/\s+/g, "-")
    .replace(/[^a-z0-9-]/g, "");
  return postcode ? `${slug}-${postcode}` : slug;
}

export function parseSuburbSlug(slug) {
  const match = slug.match(/-(\d{4})$/);
  if (match) {
    return {
      suburbSlug: slug.slice(0, -(match[0].length)),
      postcode: match[1],
    };
  }
  return { suburbSlug: slug, postcode: null };
}

export function slugToSuburbName(rawSlug) {
  const target = rawSlug.replace(/-/g, " ");
  const key = Object.keys(SUBURB_POSTCODES).find(
    (k) => k.toLowerCase() === target.toLowerCase()
  );
  if (key) return key;
  return target
    .split(" ")
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ");
}
